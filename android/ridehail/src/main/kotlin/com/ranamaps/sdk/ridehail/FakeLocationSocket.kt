package com.ranamaps.sdk.ridehail

import com.ranamaps.sdk.client.LatLng
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Job
import kotlinx.coroutines.delay
import kotlinx.coroutines.flow.MutableSharedFlow
import kotlinx.coroutines.flow.SharedFlow
import kotlinx.coroutines.isActive
import kotlinx.coroutines.launch
import org.json.JSONObject
import java.util.concurrent.atomic.AtomicInteger
import kotlin.math.atan2
import kotlin.math.cos
import kotlin.math.hypot
import kotlin.random.Random

/**
 * Mimics a driver-tracking websocket. It emits JSON text frames
 * `{"lat":..,"lng":..,"speed":..,"heading":..,"accuracy":..,"ts":..}` on a timer, generated by walking the route geometry
 * at a fixed speed with +-3 m of GPS noise. The "driver" keeps moving while updates are dropped, so a gap shows up as a jump
 * in the next frame, exactly like a real connection that stalled.
 */
class FakeLocationSocket(
    route: List<LatLng>,
    private val speedMetresPerSecond: Double,
    @Volatile var intervalMs: Long = 5_000,
    private val random: Random = Random.Default,
) {
    private val _messages = MutableSharedFlow<String>(extraBufferCapacity = 64)
    /** Raw text frames, as a client would receive them. */
    val messages: SharedFlow<String> = _messages

    private val skip = AtomicInteger(0)
    private val cumulative = DoubleArray(route.size)
    private val points = route
    val totalMetres: Double

    init {
        for (i in 1 until route.size) cumulative[i] = cumulative[i - 1] + metres(route[i - 1], route[i])
        totalMetres = cumulative.last()
    }

    /** The next [count] scheduled frames are not sent. */
    fun dropNext(count: Int) { skip.set(count) }
    val pendingDrops: Int get() = skip.get()

    /** Starts emitting; [onClosed] runs once the end of the route is reached. */
    fun connect(scope: CoroutineScope, onClosed: () -> Unit): Job = scope.launch {
        var progress = 0.0
        var last = System.nanoTime()
        _messages.emit(frame(progress))
        while (isActive) {
            delay(intervalMs)
            val now = System.nanoTime()
            progress = (progress + speedMetresPerSecond * (now - last) / 1e9).coerceAtMost(totalMetres)
            last = now
            if (skip.get() > 0) { skip.decrementAndGet() } else _messages.emit(frame(progress))
            if (progress >= totalMetres) { if (skip.getAndSet(0) > 0) _messages.emit(frame(progress)); onClosed(); break }
        }
    }

    private fun frame(progress: Double): String {
        val here = pointAt(progress)
        val ahead = pointAt(progress + 10); val behind = pointAt(progress - 10)
        val heading = (Math.toDegrees(atan2((ahead.lng - behind.lng) * cos(Math.toRadians(here.lat)), ahead.lat - behind.lat)) + 360) % 360
        val north = random.nextDouble(-3.0, 3.0); val east = random.nextDouble(-3.0, 3.0)
        val lat = here.lat + north / 111_320.0
        val lng = here.lng + east / (111_320.0 * cos(Math.toRadians(here.lat)))
        val speed = if (progress >= totalMetres) 0.0 else speedMetresPerSecond * random.nextDouble(0.92, 1.08)
        return JSONObject().put("lat", lat).put("lng", lng).put("speed", speed).put("heading", heading)
            .put("accuracy", random.nextDouble(3.0, 6.0)).put("ts", System.currentTimeMillis()).toString()
    }

    private fun pointAt(distance: Double): LatLng {
        val d = distance.coerceIn(0.0, totalMetres)
        var low = 1; var high = points.lastIndex
        while (low < high) { val mid = (low + high) / 2; if (cumulative[mid] < d) low = mid + 1 else high = mid }
        val length = cumulative[low] - cumulative[low - 1]
        val t = if (length <= 0) 0.0 else (d - cumulative[low - 1]) / length
        val a = points[low - 1]; val b = points[low]
        return LatLng(a.lat + (b.lat - a.lat) * t, a.lng + (b.lng - a.lng) * t)
    }

    companion object {
        fun metres(a: LatLng, b: LatLng): Double =
            hypot((b.lat - a.lat) * 111_320.0, (b.lng - a.lng) * 111_320.0 * cos(Math.toRadians((a.lat + b.lat) / 2)))
    }
}
